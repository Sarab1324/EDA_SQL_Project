-- Find the date of the first and last order

select MIN(nullif(order_date, '')::DATE) as first_order_date,
MAX(nullif(order_date, '')::DATE) as last_order_date,
AGE(MAX(nullif(order_date, '')::DATE), MIN(nullif(order_date, '')::DATE)) order_range_year
from fact_sales;

-- Find the youngest and the oldest customers

select MIN(nullif(birthdate, '')::DATE) as oldest_birthdate,
AGE(current_date,  MIN(nullif(birthdate, '')::DATE)) oldest_date,
MAX(nullif(birthdate, '')::DATE) as oldest_birthdate,
AGE(current_date,  MAX(nullif(birthdate, '')::DATE)) youngest_date
from dim_customers dc;

