-- Find total customers by country
SELECT
dc.country, 
COUNT(DISTINCT dc.customer_key) total_customers 
FROM dim_customers dc 
GROUP BY country 
ORDER BY total_customers DESC;

-- Find total customers by gender
SELECT
dc.gender , 
COUNT(DISTINCT dc.customer_key) total_customers 
FROM dim_customers dc 
GROUP BY gender
ORDER BY total_customers DESC;

-- Find total customers by country
SELECT
dp.category, 
COUNT(DISTINCT dp.product_key) total_products 
FROM dim_products dp  
GROUP BY dp.category 
ORDER BY total_products  DESC; 

-- What is the average costs in each category?
SELECT
dp.category, 
ROUND(AVG(dp.cost), 0) avg_cost
FROM dim_products dp  
GROUP BY dp.category 
ORDER BY avg_cost  DESC;

-- What is the total revenue generated for each category
SELECT
dp.category,
sum(t.sales_amount) total_revenue
FROM fact_sales t 
LEFT JOIN dim_products dp 
ON t.product_key = dp.product_key  
GROUP BY dp.category 
ORDER BY total_revenue  DESC; 

-- What is the total revenue generated by each customer
SELECT
dc.customer_key,
dc.first_name,
sum(t.sales_amount) total_revenue
FROM fact_sales t 
LEFT JOIN dim_customers dc 
ON t.customer_key  = dc.customer_key  
GROUP BY dc.customer_key, dc.first_name 
ORDER BY total_revenue  DESC; 

-- What is the distribution of sold items across countries?
SELECT
dc.country,
sum(t.quantity) total_sold_items
FROM fact_sales t 
LEFT JOIN dim_customers dc 
ON t.customer_key  = dc.customer_key  
GROUP BY dc.country
ORDER BY total_sold_items  DESC; 

