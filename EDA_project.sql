-- Which 5 products generate the highest revenue?
SELECT
dp.product_name,
sum(t.sales_amount) total_revenue
FROM fact_sales t 
LEFT JOIN dim_products dp 
ON t.product_key = dp.product_key  
GROUP BY dp.product_name
ORDER BY total_revenue  DESC
LIMIT 5;

--Using the window function
SELECT * FROM (
	SELECT
	dp.product_name,
	sum(t.sales_amount) total_revenue,
	row_number() over(ORDER BY sum(t.sales_amount) desc) ranking
	FROM fact_sales t 
	LEFT JOIN dim_products dp 
	ON t.product_key = dp.product_key  
	GROUP BY dp.product_name
	)s WHERE s.ranking <=5;



--What are the  worst-performing products in term of sales?
